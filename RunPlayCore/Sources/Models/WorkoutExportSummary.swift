public struct SegmentExport: Codable, Sendable {
    public let type: String
    public let title: String
    public let description: String
    public let startDistanceKm: Double
    public let endDistanceKm: Double
    public let distanceKm: Double
    public let startElapsedSeconds: Double
    public let endElapsedSeconds: Double
    public let activeDurationSeconds: Double
    public let elapsedDurationSeconds: Double
    public let activePaceSecondsPerKilometer: Double?
    /// Additive compatibility aliases use active semantics.
    public let durationSeconds: Double
    public let paceSecondsPerKilometer: Double?
    /// Defines whether the corrected elevation value is signed change,
    /// threshold-confirmed ascent, or threshold-confirmed descent.
    public let elevationMetric: String?
    /// Value matching `elevationMetric`; ascent and descent are positive magnitudes.
    public let correctedElevationValueMeters: Double?
    /// Backward-compatible signed-change field. Descents remain negative here.
    public let elevationDeltaMeters: Double?
    public let averageHeartRateBPM: Double?
    public let averagePowerWatts: Double?

    public init(segment: SegmentHighlight) {
        type = segment.type.rawValue
        title = segment.title
        description = segment.subtitle
        startDistanceKm = ExportMetricSanitizer.nonNegative(segment.startDistanceMeters) / 1000
        endDistanceKm = ExportMetricSanitizer.nonNegative(segment.endDistanceMeters) / 1000
        distanceKm = ExportMetricSanitizer.nonNegative(segment.distanceMeters) / 1000
        startElapsedSeconds = ExportMetricSanitizer.nonNegative(segment.startElapsedSeconds)
        endElapsedSeconds = ExportMetricSanitizer.nonNegative(segment.endElapsedSeconds)
        activeDurationSeconds = ExportMetricSanitizer.nonNegative(segment.activeDurationSeconds)
        elapsedDurationSeconds = ExportMetricSanitizer.nonNegative(segment.elapsedDurationSeconds)
        activePaceSecondsPerKilometer = ExportMetricSanitizer.positiveOptional(segment.paceSecondsPerKilometer)
        durationSeconds = activeDurationSeconds
        paceSecondsPerKilometer = activePaceSecondsPerKilometer
        elevationMetric = Self.elevationMetric(for: segment)
        correctedElevationValueMeters = Self.correctedElevationValue(for: segment)
        elevationDeltaMeters = ExportMetricSanitizer.optional(segment.elevationDeltaMeters)
        averageHeartRateBPM = ExportMetricSanitizer.optional(segment.averageHeartRate)
        averagePowerWatts = ExportMetricSanitizer.optional(segment.averagePowerWatts)
    }

    private static func elevationMetric(for segment: SegmentHighlight) -> String? {
        guard segment.elevationDeltaMeters != nil else { return nil }
        switch segment.type {
        case .biggestClimb:
            return "corrected_ascent"
        case .biggestDescent:
            return "corrected_descent"
        case .fastest400m, .fastest1km, .slowest1km, .slowdown, .custom:
            return "corrected_signed_change"
        }
    }

    private static func correctedElevationValue(for segment: SegmentHighlight) -> Double? {
        guard let value = ExportMetricSanitizer.optional(segment.elevationDeltaMeters) else {
            return nil
        }
        switch segment.type {
        case .biggestClimb:
            return value >= 0 ? value : nil
        case .biggestDescent:
            return value <= 0 ? -value : nil
        case .fastest400m, .fastest1km, .slowest1km, .slowdown, .custom:
            return value
        }
    }
}

private enum ExportMetricSanitizer {
    static func nonNegative(_ value: Double) -> Double {
        value.isFinite ? max(0, value) : 0
    }

    static func optional(_ value: Double?) -> Double? {
        guard let value, value.isFinite else { return nil }
        return value
    }

    static func positiveOptional(_ value: Double?) -> Double? {
        guard let value, value.isFinite, value > 0 else { return nil }
        return value
    }
}
